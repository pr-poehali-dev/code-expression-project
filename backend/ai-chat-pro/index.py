    try:
        body = json.loads(event.get("body") or "{}")
    except Exception:
        return {"statusCode": 400, "headers": CORS, "body": json.dumps({"error": "Invalid JSON"})}

    if body.get("token") != ADMIN_TOKEN:
        return {"statusCode": 403, "headers": CORS, "body": json.dumps({"error": "Forbidden"})}

    role = body.get("role", "marketer")
    messages = body.get("messages", [])

    if not messages:
        return {"statusCode": 400, "headers": CORS, "body": json.dumps({"error": "messages required"})}

    system_prompt = ROLE_PROMPTS.get(role, ROLE_PROMPTS["marketer"])
    reply = call_ai(system_prompt, messages)

    return {
        "statusCode": 200,
        "headers": CORS,
        "body": json.dumps({"reply": reply, "role": role}, ensure_ascii=False),
    }