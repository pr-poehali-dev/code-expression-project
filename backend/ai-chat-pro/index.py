def call_ai(system_prompt: str, messages: list) -> str:
    api_key = os.environ.get("POLZA_AI_API_KEY", "")
    payload = json.dumps({
        "model": "openai/gpt-4.1",
        "messages": [{"role": "system", "content": system_prompt}] + messages,
        "temperature": 0.8,
        "max_tokens": 2500,
    }).encode("utf-8")
    req = urllib.request.Request(
        "https://polza.ai/api/v1/chat/completions",
        data=payload,
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=55) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    return data["choices"][0]["message"]["content"].strip()


CORS = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
}


def handler(event: dict, context) -> dict:
    """Продвинутый ИИ-чат с выбором роли (маркетолог, блогер, финансист, философ, программист, бизнесмен). Только для администратора."""
    if event.get("httpMethod") == "OPTIONS":
        return {"statusCode": 200, "headers": CORS, "body": ""}

    try:
        body = json.loads(event.get("body") or "{}")
    except Exception:
        return {"statusCode": 400, "headers": CORS, "body": json.dumps({"error": "Invalid JSON"})}

    if body.get("token") != ADMIN_TOKEN:
        return {"statusCode": 403, "headers": CORS, "body": json.dumps({"error": "Forbidden"})}

    role = body.get("role", "marketer")
    messages = body.get("messages", [])

    if not messages:
        return {"statusCode": 400, "headers": CORS, "body": json.dumps({"error": "messages required"})}

    system_prompt = ROLE_PROMPTS.get(role, ROLE_PROMPTS["marketer"])
    reply = call_ai(system_prompt, messages)

    return {
        "statusCode": 200,
        "headers": CORS,
        "body": json.dumps({"reply": reply, "role": role}, ensure_ascii=False),
    }
