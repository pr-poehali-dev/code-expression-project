def handler(event: dict, context) -> dict:
    """ИИ-ассистент представителя Dok Диалог по работе с салонами"""
    cors = {
        "Access-Control-Allow-Origin": "*",
        "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
        "Access-Control-Allow-Headers": "Content-Type, X-Session-Id",
    }

    if event.get("httpMethod") == "OPTIONS":
        return {"statusCode": 200, "headers": cors, "body": ""}

    body = json.loads(event.get("body") or "{}")
    session_id = (event.get("headers") or {}).get("X-Session-Id", "")

    if not session_id:
        return {"statusCode": 403, "headers": cors, "body": json.dumps({"error": "Не авторизован"})}

    import psycopg2
    import psycopg2.extras

    SCHEMA = "t_p84565078_code_expression_proj"

    conn = psycopg2.connect(os.environ["DATABASE_URL"])
    try:
        cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
        cur.execute(
            f"SELECT u.* FROM {SCHEMA}.lk_sessions s JOIN {SCHEMA}.lk_users u ON u.id = s.user_id "
            f"WHERE s.id = %s AND s.expires_at > NOW() AND u.is_active = TRUE",
            (session_id,)
        )
        user = cur.fetchone()
    finally:
        conn.close()

    if not user:
        return {"statusCode": 401, "headers": cors, "body": json.dumps({"error": "Сессия не найдена"})}

    if not user.get("is_representative") and not user.get("is_admin"):
        return {"statusCode": 403, "headers": cors, "body": json.dumps({"error": "Нет доступа"})}

    messages = body.get("messages", [])
    if not messages:
        return {"statusCode": 400, "headers": cors, "body": json.dumps({"error": "No messages"})}

    client = OpenAI(
        base_url="https://polza.ai/api/v1",
        api_key=os.environ["OPENAI_API_KEY"],
    )

    full_messages = [{"role": "system", "content": SYSTEM_PROMPT}] + messages

    completion = client.chat.completions.create(
        model="openai/gpt-4.1-mini",
        messages=full_messages,
        max_tokens=4096,
    )

    reply = completion.choices[0].message.content

    return {
        "statusCode": 200,
        "headers": {**cors, "Content-Type": "application/json"},
        "body": json.dumps({"reply": reply}, ensure_ascii=False),
    }
