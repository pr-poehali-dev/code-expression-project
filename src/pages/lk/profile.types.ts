export type ProfileIndexKey =
  | "IFZ"  // Индекс финансовой зрелости
  | "IDT"  // Индекс денежной тревожности
  | "IN"   // Индекс накопления
  | "IFD"  // Индекс финансовой дисциплины
  | "IDM"  // Индекс дефицитного мышления
  | "IDR"  // Индекс денежной реализации
  | "IIT"  // Индекс импульсивных трат
  | "IDS"; // Индекс денежной самооценки

export type ProfileScores = Record<ProfileIndexKey, number>;

