import { useLkAuth } from "@/contexts/LkAuthContext";

const REPLACEMENTS: [RegExp, string][] = [
  [/Мышление с премиум-клиентами/g, "Мышление в работе с клиентами"],
  [/Индекс готовности к премиум-клиентам/g, "Индекс уверенности в работе с клиентами"],
  [/Что мешает работать с премиум-клиентами/g, "Что мешает уверенно работать с клиентами"],
  [/Коммуникация с премиум-клиентом/g, "Коммуникация со сложным клиентом"],
  [/работы с премиум-клиентами/g, "работы с клиентами"],
  [/Премиум-клиент чувствует/g, "Клиент чувствует"],
  [/теряют премиум-клиентов/g, "теряют хороших клиентов"],
  [/клиентами высокого сегмента/g, "клиентами"],
  [/Осознанные клиенты высокого уровня/g, "Осознанные клиенты, которым подходит моя работа"],
  [/Если клиент отменяет запись:/g, "Если клиент отменяет встречу или заказ:"],
  [/После сессии с трудным клиентом/g, "После встречи с трудным клиентом"],
  [/для 90-минутного сеанса/g, "для 90-минутной встречи или занятия"],
  [/Средний чек за сессию\/услугу/g, "Средний чек за услугу, занятие или заказ"],
  [/Средняя длительность сессии/g, "Средняя длительность одной услуги"],
  [/от других специалистов по телу в вашем городе/g, "от других специалистов вашего направления в вашем городе"],
  [/реклама медицинских и массажных услуг в России регулируется, поэтому продвигай экспертность и результаты, а не «лечение»/g, "реклама некоторых услуг в России регулируется, поэтому продвигай экспертность и понятную пользу, а не гарантии результата"],
  [/превратить «я массажист» в конкретное предложение ценности/g, "превратить «я специалист» в конкретное предложение ценности"],
  [/в управлении доходом специалиста по телу/g, "в управлении доходом специалиста"],
];

export function adaptText(text: string, on: boolean): string {
  if (!on || !text) return text;
  return REPLACEMENTS.reduce((acc, [re, to]) => acc.replace(re, to), text);
}

export function useIsOtherSpecialist(): boolean {
  const { user } = useLkAuth();
  return user?.specialization === "other_specialist";
}

export function adaptNavLabel(id: string, label: string, on: boolean): string {
  if (on && id === "tools") return "Развитие специалиста";
  return label;
}
