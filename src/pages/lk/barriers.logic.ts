import { BarrierKey, BARRIER_QUESTIONS, BARRIER_MAX } from "./barriers.types";

export type BarrierIndexMap = Record<BarrierKey, number>;

export function calcBarrierIndexes(answers: Record<number, number>): BarrierIndexMap {
  const raw: Record<BarrierKey, number> = {
    IVO: 0, ISS: 0, ISD: 0, IDO: 0, IIR: 0, IEI: 0, ISP: 0, IPZ_raw: 0,
  };

  BARRIER_QUESTIONS.forEach(q => {
    const optIdx = answers[q.id];
    if (optIdx === undefined) return;
    const scores = q.options[optIdx].scores;
    (Object.keys(scores) as BarrierKey[]).forEach(k => {
      raw[k] += scores[k] ?? 0;
    });
  });

  const pct = {} as BarrierIndexMap;
  (Object.keys(raw) as BarrierKey[]).forEach(k => {
    const max = BARRIER_MAX[k];
    pct[k] = max > 0 ? Math.min(100, Math.round((raw[k] / max) * 100)) : 0;
  });

  return pct;
}

// Индекс профессиональной зрелости (составной)
export function calcIPZ(idx: BarrierIndexMap): number {
  return Math.round((idx.IVO + (100 - idx.ISS) + (100 - idx.IDO) + (100 - idx.ISD)) / 4);
}

// Главный индекс внутренних барьеров (0=нет барьеров, 100=полный саботаж)
export function calcIIB(idx: BarrierIndexMap): number {
  const raw = (idx.ISS + idx.ISD + idx.ISP + idx.IDO + idx.IIR + idx.IEI) / 6;
  return Math.max(0, Math.min(100, Math.round(raw)));
}

export function getBarrierScaleLabel(iib: number): { label: string; color: string } {
  if (iib < 30) return { label: "Низкий уровень барьеров", color: "#14b8a6" };
  if (iib < 50) return { label: "Скрытые ограничения", color: "#22c55e" };
  if (iib < 70) return { label: "Выраженные блоки", color: "#eab308" };
  if (iib < 85) return { label: "Сильное ограничение роста", color: "#f97316" };
  return { label: "Внутренний саботаж", color: "#ef4444" };
}

// Определяет главный и вторичный барьер
export function getPrimaryBarrier(idx: BarrierIndexMap): { primary: string; secondary: string } {
  const barriers: { label: string; value: number }[] = [
    { label: "Синдром самозванца",        value: idx.ISS },
    { label: "Страх денег",               value: idx.ISD },
    { label: "Страх проявленности",       value: idx.ISP },
    { label: "Зависимость от оценки",     value: idx.IDO },
    { label: "Избегание роста",           value: idx.IIR },
    { label: "Эмоциональное истощение",   value: idx.IEI },
  ];
  const sorted = [...barriers].sort((a, b) => b.value - a.value);
  return { primary: sorted[0].label, secondary: sorted[1].label };
}

